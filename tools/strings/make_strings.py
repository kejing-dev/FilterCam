#!/usr/bin/env python3
"""Writes res/values/strings.xml (English, the default) and res/values-zh/strings.xml from strings.tsv
(key <TAB> English <TAB> Chinese). Copy follows design copy.* and content.tone; edit the TSV, then run:

    python tools/strings/make_strings.py
"""
import os
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "app", "src", "main", "res")


def esc(s: str) -> str:
    s = escape(s).replace("'", "\\'").replace('"', '\\"')
    if s[:1] in ("?", "@"):
        s = "\\" + s
    return s


rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(HERE, "strings.tsv"), encoding="utf-8") if l.strip()]
for folder, col in (("values", 1), ("values-zh", 2)):
    os.makedirs(os.path.join(RES, folder), exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- generated by tools/strings/make_strings.py from strings.tsv -->", "<resources>"]
    for r in rows:
        out.append(f'    <string name="{r[0]}">{esc(r[col])}</string>')
    out.append("</resources>\n")
    open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(len(rows), "strings")
