#!/usr/bin/env python3
"""Generates the built-in 33^3 .cube LUTs (design filters.authoring) from formulas: colour matrix, per-channel curves,
white balance shift and split toning. Nothing is copied from a commercial LUT. Writes app/src/main/assets/luts/*.cube.

    python tools/filters/make_luts.py
"""
import os

import numpy as np

N = 33
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main", "assets", "luts")


def lum(c):
    return c[..., 0] * 0.2126 + c[..., 1] * 0.7152 + c[..., 2] * 0.0722


def smooth(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


def sat(c, k):
    l = lum(c)[..., None]
    return l + (c - l) * k


def scurve(c, k):
    """Contrast around mid grey; k > 0 harder, k < 0 softer."""
    s = c + k * (c - 0.5) * (1 - np.abs(2 * c - 1))  # cubic-ish, keeps 0 and 1
    return s


def gold200(c):
    c = c * np.array([1.06, 1.0, 0.88]) + np.array([0.02, 0.012, 0.0])
    l = lum(c)[..., None]
    h = smooth(0.55, 1.0, l)
    s = 1 - smooth(0.0, 0.35, l)
    c = c + h * np.array([0.035, 0.025, -0.03]) + s * np.array([-0.02, 0.012, 0.018])
    c = sat(c, 1.10)
    return scurve(c, 0.22)


def ccd_cool(c):
    c = c * np.array([0.98, 0.95, 1.08]) + np.array([0.02, 0.0, 0.025])
    c = sat(c, 1.15)
    c = scurve(c, 0.35)
    l = lum(c)[..., None]
    blow = smooth(0.78, 0.98, l)
    return c + (1 - c) * blow * 0.6


def trix(c):
    g = c[..., 0] * 0.45 + c[..., 1] * 0.45 + c[..., 2] * 0.10
    g = scurve(scurve(g, 0.6), 0.4)
    g = g + smooth(0.8, 1.0, g) * 0.05
    return np.stack([g, g, g], axis=-1)


def cyber_split(c):
    teal = np.array([0x0E, 0x6E, 0x8E]) / 255.0
    pink = np.array([0xFF, 0x3F, 0xA4]) / 255.0
    l = lum(c)[..., None]
    shadows = 1 - smooth(0.15, 0.55, l)
    c = sat(c, 1.0 - 0.2 * shadows)
    t = smooth(0.25, 0.85, l)
    tone = teal * (1 - t) + pink * t
    # soft light of the tone over the picture
    soft = np.where(tone < 0.5, 2 * c * tone + c * c * (1 - 2 * tone), 2 * c * (1 - tone) + np.sqrt(np.clip(c, 0, 1)) * (2 * tone - 1))
    c = c * 0.4 + soft * 0.6
    return scurve(c, 0.3)


def instant(c):
    c = scurve(c, -0.25)
    c = c + np.array([0.02, 0.035, -0.035])
    return sat(c, 0.82)


def y2k_cool(c):
    c = c * np.array([0.92, 0.98, 1.12]) + np.array([0.0, 0.01, 0.03])
    c = sat(c, 1.2)
    return scurve(c, 0.25)


LUTS = {"gold200": gold200, "ccd_cool": ccd_cool, "trix": trix, "cyber_split": cyber_split, "instant": instant, "y2k_cool": y2k_cool}


def write(name, f):
    i = np.linspace(0, 1, N)
    b, g, r = np.meshgrid(i, i, i, indexing="ij")  # r fastest in the flattened order
    c = np.stack([r, g, b], axis=-1)
    out = np.clip(f(c), 0, 1).reshape(-1, 3)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".cube"), "w", newline="\n") as fh:
        fh.write(f'TITLE "{name}"\n# Filter Cam built-in LUT, generated by tools/filters/make_luts.py\nLUT_3D_SIZE {N}\n')
        for v in out:
            fh.write("%.6f %.6f %.6f\n" % tuple(v))


if __name__ == "__main__":
    for k, f in LUTS.items():
        write(k, f)
        print("wrote", k)
